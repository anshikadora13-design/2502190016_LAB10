def identify_overdue_pumps(records, current_date):
    """
    Filters and returns pumps that are overdue for maintenance.
    Uses a dictionary to track the latest maintenance date per pump.
    """
    # Example logic using dictionaries
    overdue_pumps = []
    for record in records:
        # Check if record is a pump and if current_date exceeds next scheduled date
        if record.get('type') == 'pump':
            scheduled_date = record.get('next_service')
            if scheduled_date and scheduled_date < current_date:
                overdue_pumps.append(record)
    return overdue_pumps

def rank_pumps_by_urgency(overdue_pumps):
    """
    Ranks the overdue pumps using sorted with a custom lambda key.
    Pumps with the oldest 'next_service' date are ranked first (highest urgency).
    """
    return sorted(overdue_pumps, key=lambda x: x.get('next_service'))

def process_records_decision(records, current_date):
    """
    Main coordinator function for Job A.
    Combines the helper functions to return a final decision dictionary.
    """
    overdue = identify_overdue_pumps(records, current_date)
    ranked_overdue = rank_pumps_by_urgency(overdue)

    decision = {
        'total_scanned': len(records),
        'overdue_count': len(ranked_overdue),
        'primary_attention_needed': ranked_overdue[0] if ranked_overdue else None,
        'full_priority_list': ranked_overdue
    }
    return decision

